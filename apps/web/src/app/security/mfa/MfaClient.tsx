"use client";

import { useEffect, useRef, useState } from "react";
import { useRouter } from "next/navigation";
import { createClient } from "@/lib/supabase/client";
import { logout } from "@/app/auth/actions";

interface Enrollment {
  factorId: string;
  qr: string;
  secret: string;
}

export function MfaClient({ hasFactor }: { hasFactor: boolean }) {
  const router = useRouter();
  const [factorId, setFactorId] = useState<string | null>(null);
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [code, setCode] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const started = useRef(false);

  // Prepare either a verification (existing factor) or a fresh enrollment (once: React dev mode runs effects twice).
  useEffect(() => {
    if (started.current) return;
    started.current = true;
    const supabase = createClient();
    (async () => {
      const { data: factors, error: listErr } = await supabase.auth.mfa.listFactors();
      if (listErr) return setError(listErr.message);

      const verified = factors?.totp?.find((f) => f.status === "verified");
      if (verified) return setFactorId(verified.id);
      if (hasFactor) return setError("Could not find your authenticator. Please sign out and back in.");

      // Remove abandoned, never-verified attempts so enrollment can start cleanly.
      for (const f of factors?.all ?? []) {
        if (f.factor_type === "totp" && f.status === "unverified") await supabase.auth.mfa.unenroll({ factorId: f.id });
      }
      const { data, error: enrollErr } = await supabase.auth.mfa.enroll({ factorType: "totp", friendlyName: `Authenticator ${new Date().toISOString().slice(0, 16)}` });
      if (enrollErr || !data) return setError(enrollErr?.message ?? "Could not start enrollment.");
      setFactorId(data.id);
      setEnrollment({ factorId: data.id, qr: data.totp.qr_code, secret: data.totp.secret });
    })();
  }, [hasFactor]);

  async function submit(e: React.FormEvent) {
    e.preventDefault();
    if (!factorId) return;
    setBusy(true);
    setError(null);
    const supabase = createClient();
    const { error: verifyErr } = await supabase.auth.mfa.challengeAndVerify({ factorId, code: code.trim() });
    setBusy(false);
    if (verifyErr) {
      setError(verifyErr.message);
      setCode("");
      return;
    }
    router.replace("/dashboard");
    router.refresh();
  }

  return (
    <div className="space-y-4">
      {enrollment && (
        <div className="space-y-3">
          <p className="text-sm">1. Scan this QR code with your authenticator app.</p>
          {/* qr_code is an SVG data URI generated by Supabase Auth */}
          <img src={enrollment.qr} alt="QR code for your authenticator app" className="w-48 h-48 bg-white p-2 rounded-lg" />
          <p className="text-xs text-muted-foreground break-all">
            Cannot scan? Enter this key manually: <span data-testid="mfa-secret" className="font-mono">{enrollment.secret}</span>
          </p>
          <p className="text-sm">2. Enter the 6-digit code it shows.</p>
        </div>
      )}
      {!enrollment && factorId && <p className="text-sm">Enter the 6-digit code from your authenticator app.</p>}

      <form onSubmit={submit} className="space-y-3">
        <label className="label" htmlFor="mfa-code">
          Authentication code
        </label>
        <input
          id="mfa-code"
          className="input"
          inputMode="numeric"
          autoComplete="one-time-code"
          pattern="[0-9]{6}"
          maxLength={6}
          required
          value={code}
          onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))}
          disabled={!factorId}
        />
        {error && (
          <p role="alert" className="text-sm text-red-400">
            {error}
          </p>
        )}
        <button type="submit" disabled={busy || !factorId || code.length !== 6} className="btn-primary w-full">
          {busy ? "Verifying..." : "Verify and continue"}
        </button>
      </form>

      <form action={logout}>
        <button type="submit" className="text-xs text-muted-foreground underline">
          Sign out
        </button>
      </form>
    </div>
  );
}
